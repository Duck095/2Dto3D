package com.exe.morphia3d.repository;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.MigrationVersion;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.sql.DatabaseMetaData;
import java.sql.ResultSet;

import static org.assertj.core.api.Assertions.assertThat;

@Testcontainers(disabledWithoutDocker = true)
class MediaAssetMigrationPostgresTest {

    @Container
    private static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine")
            .withDatabaseName("media_migration")
            .withUsername("test")
            .withPassword("test");

    @Test
    void v2IsAdditiveAndUsesRestrictiveReferencesOnPostgresql() throws Exception {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE model_3d (model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "file_path_3d VARCHAR(500))");
        jdbc.execute("CREATE TABLE model_images (image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "image_path VARCHAR(500))");
        jdbc.update("INSERT INTO model_3d (file_path_3d) VALUES (?)", "legacy/models/chair.glb");
        jdbc.update("INSERT INTO model_images (image_path) VALUES (?)", "legacy/images/chair-cover");

        Flyway flyway = Flyway.configure()
                .dataSource(dataSource)
                .locations("classpath:db/migration")
                .baselineVersion("1")
                .target(MigrationVersion.fromVersion("2"))
                .load();
        flyway.baseline();
        int migrationsApplied = flyway.migrate().migrationsExecuted;

        assertThat(migrationsApplied).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT file_path_3d FROM model_3d", String.class))
                .isEqualTo("legacy/models/chair.glb");
        assertThat(jdbc.queryForObject("SELECT image_path FROM model_images", String.class))
                .isEqualTo("legacy/images/chair-cover");
        assertThat(jdbc.queryForObject("SELECT media_asset_id IS NULL FROM model_3d", Boolean.class)).isTrue();
        assertThat(jdbc.queryForObject("SELECT media_asset_id IS NULL FROM model_images", Boolean.class)).isTrue();

        try (var connection = dataSource.getConnection()) {
            DatabaseMetaData metadata = connection.getMetaData();
            assertDeleteRuleIsRestrict(metadata, "model_3d", "fk_model_3d_media_asset");
            assertDeleteRuleIsRestrict(metadata, "model_images", "fk_model_images_media_asset");
        }
    }

    private void assertDeleteRuleIsRestrict(DatabaseMetaData metadata, String table, String constraint)
            throws Exception {
        try (ResultSet keys = metadata.getImportedKeys(null, "public", table)) {
            boolean found = false;
            while (keys.next()) {
                if (constraint.equalsIgnoreCase(keys.getString("FK_NAME"))) {
                    found = true;
                    assertThat((int) keys.getShort("DELETE_RULE"))
                            .isEqualTo(DatabaseMetaData.importedKeyRestrict);
                }
            }
            assertThat(found).as("foreign key %s on %s", constraint, table).isTrue();
        }
    }
}
