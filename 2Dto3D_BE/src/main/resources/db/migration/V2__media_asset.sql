CREATE TABLE media_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL,
    media_kind VARCHAR(16) NOT NULL,
    provider VARCHAR(32) NOT NULL,
    cloud_name VARCHAR(255) NOT NULL,
    provider_asset_id VARCHAR(255),
    public_id VARCHAR(512) NOT NULL,
    resource_type VARCHAR(16) NOT NULL,
    delivery_type VARCHAR(32) NOT NULL,
    format VARCHAR(32) NOT NULL,
    byte_count BIGINT NOT NULL,
    provider_version BIGINT,
    secure_url VARCHAR(2048),
    state VARCHAR(32) NOT NULL,
    lease_owner VARCHAR(128),
    lease_token UUID,
    lease_until TIMESTAMP WITH TIME ZONE,
    retry_count INTEGER NOT NULL DEFAULT 0,
    last_error_code VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_media_asset_kind CHECK (media_kind IN ('IMAGE', 'MODEL_3D')),
    CONSTRAINT ck_media_asset_state CHECK (state IN (
        'PENDING_UPLOAD', 'UPLOADING', 'READY', 'ATTACHED',
        'CLEANUP_PENDING', 'CLEANUP_LEASED', 'DELETED')),
    CONSTRAINT ck_media_asset_byte_count CHECK (byte_count > 0),
    CONSTRAINT ck_media_asset_retry_count CHECK (retry_count >= 0),
    CONSTRAINT uq_media_asset_provider_public_identity UNIQUE
        (provider, cloud_name, resource_type, delivery_type, public_id),
    CONSTRAINT uq_media_asset_provider_asset_identity UNIQUE
        (provider, cloud_name, provider_asset_id)
);

CREATE INDEX idx_media_asset_operation_id ON media_asset (operation_id);
CREATE INDEX idx_media_asset_state_created_at ON media_asset (state, created_at);

ALTER TABLE model_3d ADD COLUMN media_asset_id BIGINT;
ALTER TABLE model_3d ADD CONSTRAINT fk_model_3d_media_asset
    FOREIGN KEY (media_asset_id) REFERENCES media_asset (id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX uq_model_3d_media_asset ON model_3d (media_asset_id);

ALTER TABLE model_images ADD COLUMN media_asset_id BIGINT;
ALTER TABLE model_images ADD CONSTRAINT fk_model_images_media_asset
    FOREIGN KEY (media_asset_id) REFERENCES media_asset (id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX uq_model_images_media_asset ON model_images (media_asset_id);
