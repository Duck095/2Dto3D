CREATE TABLE staff_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    employee_number VARCHAR(32) NOT NULL,
    department VARCHAR(100) NOT NULL,
    job_title VARCHAR(120) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    joined_at DATE NOT NULL,
    created_by INTEGER NOT NULL,
    updated_by INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_staff_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_staff_profiles_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_staff_profiles_created_by FOREIGN KEY (created_by)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_staff_profiles_updated_by FOREIGN KEY (updated_by)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_staff_profiles_employee_number CHECK (
        employee_number = UPPER(employee_number)
        AND employee_number ~ '^[A-Z0-9-]{3,32}$'
    ),
    CONSTRAINT ck_staff_profiles_department CHECK (BTRIM(department) <> ''),
    CONSTRAINT ck_staff_profiles_job_title CHECK (BTRIM(job_title) <> ''),
    CONSTRAINT ck_staff_profiles_status CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED')),
    CONSTRAINT ck_staff_profiles_version CHECK (version >= 0)
);

CREATE UNIQUE INDEX uq_staff_profiles_employee_number_normalized
    ON staff_profiles (LOWER(employee_number));
CREATE INDEX idx_staff_profiles_status_department
    ON staff_profiles (status, department);
CREATE INDEX idx_staff_profiles_created_at_id
    ON staff_profiles (created_at DESC, id DESC);

CREATE TABLE staff_profile_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_profile_id BIGINT NOT NULL,
    actor_user_id INTEGER NOT NULL,
    action VARCHAR(24) NOT NULL,
    reason VARCHAR(500),
    previous_status VARCHAR(16),
    new_status VARCHAR(16),
    previous_department VARCHAR(100),
    new_department VARCHAR(100),
    previous_job_title VARCHAR(120),
    new_job_title VARCHAR(120),
    previous_joined_at DATE,
    new_joined_at DATE,
    occurred_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_staff_profile_audit_profile FOREIGN KEY (staff_profile_id)
        REFERENCES staff_profiles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_staff_profile_audit_actor FOREIGN KEY (actor_user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_staff_profile_audit_action CHECK (action IN ('CREATED', 'UPDATED', 'STATUS_CHANGED')),
    CONSTRAINT ck_staff_profile_audit_status CHECK (
        (previous_status IS NULL OR previous_status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED'))
        AND (new_status IS NULL OR new_status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED'))
    ),
    CONSTRAINT ck_staff_profile_audit_transition CHECK (
        action <> 'STATUS_CHANGED'
        OR (reason IS NOT NULL AND BTRIM(reason) <> ''
            AND previous_status IS NOT NULL AND new_status IS NOT NULL)
    )
);

CREATE INDEX idx_staff_profile_audit_profile_time
    ON staff_profile_audit (staff_profile_id, occurred_at DESC, id DESC);
