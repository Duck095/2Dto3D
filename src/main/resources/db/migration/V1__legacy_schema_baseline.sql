-- Initial pre-media application schema for fresh PostgreSQL provisioning.
-- The filename preserves the approved V1/V2 versioning contract. This is not
-- a legacy-database adoption script. V2 owns media_asset and media_asset_id.

CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(20),
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(255) DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'USER', 'DESIGNER')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'UNACTIVE'))
);

CREATE TABLE printers (
    printer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    technology VARCHAR(50),
    max_x_mm DOUBLE PRECISION,
    max_y_mm DOUBLE PRECISION,
    max_z_mm DOUBLE PRECISION,
    status VARCHAR(255) DEFAULT 'ACTIVE',
    CONSTRAINT ck_printers_status CHECK (status IN ('ACTIVE', 'FIXED', 'INACTIVE'))
);

CREATE TABLE colors (
    color_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    hex_code VARCHAR(7),
    CONSTRAINT uq_colors_name UNIQUE (name)
);

CREATE TABLE materials (
    material_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50),
    price_per_gram DOUBLE PRECISION NOT NULL,
    stock_quantity DOUBLE PRECISION NOT NULL DEFAULT 0,
    unit VARCHAR(20) NOT NULL DEFAULT 'g',
    is_available VARCHAR(255) DEFAULT 'AVAILABLE',
    CONSTRAINT ck_materials_is_available
        CHECK (is_available IN ('AVAILABLE', 'UNAVAILABLE'))
);

CREATE TABLE cart (
    cart_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uq_cart_user UNIQUE (user_id),
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT
);

CREATE TABLE ai_generation_sessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    original_image_path VARCHAR(500),
    target_size_x_mm DOUBLE PRECISION,
    target_size_y_mm DOUBLE PRECISION,
    target_size_z_mm DOUBLE PRECISION,
    prompt VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_ai_generation_sessions_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT
);

CREATE TABLE model_3d (
    model_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(255) NOT NULL,
    user_id INTEGER,
    name VARCHAR(150),
    slug VARCHAR(255),
    description VARCHAR(255),
    file_path_3d VARCHAR(500),
    size_x_mm DOUBLE PRECISION,
    size_y_mm DOUBLE PRECISION,
    size_z_mm DOUBLE PRECISION,
    weight DOUBLE PRECISION,
    category VARCHAR(100),
    model_status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    session_id INTEGER,
    variant_index INTEGER,
    CONSTRAINT ck_model_3d_source_type
        CHECK (source_type IN ('DESIGNER_MODEL', 'AI_MODEL', 'CUSTOMER_CUSTOMIZED')),
    CONSTRAINT ck_model_3d_model_status
        CHECK (model_status IN ('PENDING', 'ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_model_3d_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_model_3d_generation_session FOREIGN KEY (session_id)
        REFERENCES ai_generation_sessions (session_id) ON DELETE RESTRICT
);

CREATE TABLE model_images (
    image_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id INTEGER NOT NULL,
    image_path VARCHAR(500) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    uploaded_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_model_images_model FOREIGN KEY (model_id)
        REFERENCES model_3d (model_id) ON DELETE RESTRICT
);

CREATE TABLE model_parts (
    part_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id INTEGER NOT NULL,
    part_name VARCHAR(100) NOT NULL,
    part_key VARCHAR(100) NOT NULL,
    color_id INTEGER,
    CONSTRAINT fk_model_parts_model FOREIGN KEY (model_id)
        REFERENCES model_3d (model_id) ON DELETE RESTRICT,
    CONSTRAINT fk_model_parts_color FOREIGN KEY (color_id)
        REFERENCES colors (color_id) ON DELETE RESTRICT
);

CREATE TABLE material_colors (
    material_id INTEGER NOT NULL,
    color_id INTEGER NOT NULL,
    quantity DOUBLE PRECISION NOT NULL DEFAULT 0,
    CONSTRAINT pk_material_colors PRIMARY KEY (material_id, color_id),
    CONSTRAINT fk_material_colors_material FOREIGN KEY (material_id)
        REFERENCES materials (material_id) ON DELETE RESTRICT,
    CONSTRAINT fk_material_colors_color FOREIGN KEY (color_id)
        REFERENCES colors (color_id) ON DELETE RESTRICT
);

CREATE TABLE material_stock_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id INTEGER NOT NULL,
    change_type VARCHAR(20) NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    note VARCHAR(500),
    created_by INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    -- Preserve stock audit rows if physical deletion is attempted. Application
    -- behavior must retire materials as UNAVAILABLE instead of deleting them.
    CONSTRAINT fk_material_stock_logs_material FOREIGN KEY (material_id)
        REFERENCES materials (material_id) ON DELETE RESTRICT,
    CONSTRAINT fk_material_stock_logs_created_by FOREIGN KEY (created_by)
        REFERENCES users (user_id) ON DELETE RESTRICT
);

CREATE TABLE price_estimations (
    estimate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id INTEGER NOT NULL,
    material_id INTEGER NOT NULL,
    printer_id INTEGER NOT NULL,
    material_cost DOUBLE PRECISION,
    print_time_hours DOUBLE PRECISION,
    labor_cost DOUBLE PRECISION,
    total_price DOUBLE PRECISION,
    estimated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_price_estimations_model FOREIGN KEY (model_id)
        REFERENCES model_3d (model_id) ON DELETE RESTRICT,
    CONSTRAINT fk_price_estimations_material FOREIGN KEY (material_id)
        REFERENCES materials (material_id) ON DELETE RESTRICT,
    CONSTRAINT fk_price_estimations_printer FOREIGN KEY (printer_id)
        REFERENCES printers (printer_id) ON DELETE RESTRICT
);

CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    printer_id INTEGER NOT NULL,
    total_amount DOUBLE PRECISION NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    order_date TIMESTAMP WITHOUT TIME ZONE,
    completed_date TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT ck_orders_status
        CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCEEDED', 'CANCELED')),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_printer FOREIGN KEY (printer_id)
        REFERENCES printers (printer_id) ON DELETE RESTRICT
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    model_id INTEGER NOT NULL,
    estimate_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    price_snapshot DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_model FOREIGN KEY (model_id)
        REFERENCES model_3d (model_id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_estimate FOREIGN KEY (estimate_id)
        REFERENCES price_estimations (estimate_id) ON DELETE RESTRICT
);

CREATE TABLE cart_items (
    cart_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id INTEGER NOT NULL,
    model_id INTEGER NOT NULL,
    estimate_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    added_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id)
        REFERENCES cart (cart_id) ON DELETE RESTRICT,
    CONSTRAINT fk_cart_items_model FOREIGN KEY (model_id)
        REFERENCES model_3d (model_id) ON DELETE RESTRICT,
    CONSTRAINT fk_cart_items_estimate FOREIGN KEY (estimate_id)
        REFERENCES price_estimations (estimate_id) ON DELETE RESTRICT
);

CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    method VARCHAR(255),
    status VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    paid_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uq_payments_order UNIQUE (order_id),
    CONSTRAINT ck_payments_method CHECK (method IN ('VNPAY', 'MOMO')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE RESTRICT
);

CREATE TABLE feedback (
    feedback_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    order_item_id INTEGER NOT NULL,
    rating INTEGER,
    comment VARCHAR(255),
    image_url VARCHAR(500),
    is_visible BOOLEAN,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uq_feedback_order_item UNIQUE (order_item_id),
    CONSTRAINT fk_feedback_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_feedback_order_item FOREIGN KEY (order_item_id)
        REFERENCES order_items (order_item_id) ON DELETE RESTRICT
);

-- Support repository lookups, joins, ordering, and the public catalog filters.
CREATE INDEX idx_ai_generation_sessions_user ON ai_generation_sessions (user_id);
CREATE INDEX idx_model_3d_user ON model_3d (user_id);
CREATE INDEX idx_model_3d_session ON model_3d (session_id);
CREATE INDEX idx_model_3d_catalog
    ON model_3d (source_type, model_status, created_at DESC, model_id DESC);
CREATE INDEX idx_model_3d_category_lower ON model_3d (lower(category));
CREATE INDEX idx_model_images_model_order
    ON model_images (model_id, is_primary DESC, image_id ASC);
CREATE INDEX idx_model_parts_model ON model_parts (model_id);
CREATE INDEX idx_material_colors_color ON material_colors (color_id);
CREATE INDEX idx_material_stock_logs_material_created
    ON material_stock_logs (material_id, created_at);
CREATE INDEX idx_material_stock_logs_created_by ON material_stock_logs (created_by);
CREATE INDEX idx_price_estimations_model ON price_estimations (model_id);
CREATE INDEX idx_price_estimations_material ON price_estimations (material_id);
CREATE INDEX idx_price_estimations_printer ON price_estimations (printer_id);
CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_orders_printer ON orders (printer_id);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_model ON order_items (model_id);
CREATE INDEX idx_order_items_estimate ON order_items (estimate_id);
CREATE INDEX idx_cart_items_cart ON cart_items (cart_id);
CREATE INDEX idx_cart_items_model ON cart_items (model_id);
CREATE INDEX idx_cart_items_estimate ON cart_items (estimate_id);
CREATE INDEX idx_feedback_user ON feedback (user_id);
